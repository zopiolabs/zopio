export const PRISMA_SCHEMA_PATH = 'packages/database/prisma/schema.prisma';

function buildSingleTenantSchema(primaryEntity: string): string {
  const normalizedEntity =
    primaryEntity.trim().length > 0 ? primaryEntity.trim() : 'project';

  return `// Prisma schema generated by Zopio project setup
// Template: single-tenant
// Primary domain entity: ${normalizedEntity}

generator client {
  provider        = "prisma-client-js"
  previewFeatures = ["driverAdapters"]
  output          = "../generated/client"
}

datasource db {
  provider     = "postgresql"
  url          = env("DATABASE_URL")
  relationMode = "prisma"
}

model User {
  id        String   @id @default(cuid())
  email     String   @unique
  name      String?
  projects  Project[]
  createdAt DateTime @default(now())
  updatedAt DateTime @updatedAt
}

model Project {
  id          String   @id @default(cuid())
  name        String
  description String?
  ownerId     String
  owner       User     @relation(fields: [ownerId], references: [id])
  createdAt   DateTime @default(now())
  updatedAt   DateTime @updatedAt

  @@index([ownerId])
}
`;
}

function buildMultiTenantSchema(primaryEntity: string): string {
  const normalizedEntity =
    primaryEntity.trim().length > 0 ? primaryEntity.trim() : 'organization';

  return `// Prisma schema generated by Zopio project setup
// Template: multi-tenant
// Primary domain entity: ${normalizedEntity}

generator client {
  provider        = "prisma-client-js"
  previewFeatures = ["driverAdapters"]
  output          = "../generated/client"
}

datasource db {
  provider     = "postgresql"
  url          = env("DATABASE_URL")
  relationMode = "prisma"
}

model User {
  id           String       @id @default(cuid())
  email        String       @unique
  name         String?
  memberships  Membership[]
  createdAt    DateTime     @default(now())
  updatedAt    DateTime     @updatedAt
}

model Organization {
  id           String       @id @default(cuid())
  name         String
  slug         String       @unique
  memberships  Membership[]
  createdAt    DateTime     @default(now())
  updatedAt    DateTime     @updatedAt
}

model Membership {
  id             String        @id @default(cuid())
  userId         String
  organizationId String
  role           String        @default("member")
  user           User          @relation(fields: [userId], references: [id])
  organization   Organization  @relation(fields: [organizationId], references: [id])
  createdAt      DateTime      @default(now())
  updatedAt      DateTime      @updatedAt

  @@unique([userId, organizationId])
  @@index([organizationId])
}
`;
}

