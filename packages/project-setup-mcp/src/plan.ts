// biome-ignore lint/complexity/noExcessiveCognitiveComplexity: setup plan generation is intentionally centralized
export function generateSetupPlanAttributes(
  options: GeneratePlanOptions
): SetupPlanAttributes {
  const { sessionId, profileId, profile } = options;

  const prismaTemplate =
    profile.architecture === 'multi_tenant' ? 'multi_tenant' : 'single_tenant';

  const prismaContent =
    prismaTemplate === 'multi_tenant'
      ? buildMultiTenantSchema(profile.primaryEntity)
      : buildSingleTenantSchema(profile.primaryEntity);

  const fileChanges: PlannedFileChange[] = [];

  // Prisma schema
  fileChanges.push({
    path: PRISMA_SCHEMA_PATH,
    type: 'update',
    description:
      'Replace stub Prisma schema with a multi-tenant-ready template',
    operation: 'overwrite',
    content: prismaContent,
  });

  // Database env template
  fileChanges.push({
    path: 'packages/database/.env.example',
    type: 'update',
    description: 'Ensure DATABASE_URL is documented for the database package',
    operation: 'merge_env',
    envVars: baseEnvVars(),
  });

  // Storage package env template
  if (profile.storageLevel === 'basic') {
    fileChanges.push({
      path: 'packages/storage/.env.example',
      type: 'create',
      description:
        'Add environment template for Vercel Blob storage configuration',
      operation: 'merge_env',
      envVars: storageEnvVars(),
    });
  }

  const needsAuth = profile.authMode !== 'none';
  const needsAnalytics = profile.analyticsLevel !== 'none';
  const needsObservability =
    profile.observabilityLevel === 'standard' ||
    profile.observabilityLevel === 'extended';
  const needsRateLimiting = profile.rateLimitingLevel === 'basic';
  const needsStorage = profile.storageLevel === 'basic';

  const envRelatedApps: Array<{ app: 'app' | 'api' | 'web'; path: string }> =
    [];

  if (profile.apps.includes('app')) {
    envRelatedApps.push({ app: 'app', path: 'apps/app/.env.example' });
  }
  if (profile.apps.includes('api')) {
    envRelatedApps.push({ app: 'api', path: 'apps/api/.env.example' });
  }
  if (profile.apps.includes('web')) {
    envRelatedApps.push({ app: 'web', path: 'apps/web/.env.example' });
  }

  for (const { app, path } of envRelatedApps) {
    const envVars: EnvVarSpec[] = [];

    envVars.push(...baseEnvVars());

    if (needsAuth && (app === 'app' || app === 'api')) {
      envVars.push(...authEnvVars());
    }

    if (needsObservability) {
      envVars.push(...observabilityEnvVars());
    }

    if (needsAnalytics && (app === 'app' || app === 'web')) {
      envVars.push(...analyticsEnvVars());
    }

    if (needsStorage && (app === 'app' || app === 'api')) {
      envVars.push(...storageEnvVars());
    }

    if (needsRateLimiting && app === 'api') {
      envVars.push(...rateLimitEnvVars());
    }

    fileChanges.push({
      path,
      type: 'update',
      description: `Ensure required environment variables are present for ${path}`,
      operation: 'merge_env',
      envVars,
    });
  }

  // Example storage route (only if API app is selected and storage is needed)
  if (profile.apps.includes('api') && needsStorage) {
    fileChanges.push({
      path: 'apps/api/app/storage/example-upload/route.ts',
      type: 'create',
      description:
        'Add example route demonstrating basic Vercel Blob storage usage',
      operation: 'create_if_missing',
      content: `/**
 * SPDX-License-Identifier: MIT
 */

import { put } from '@repo/storage';

export async function POST(): Promise<Response> {
  try {
    // This route is a minimal example of using Vercel Blob through @repo/storage.
    // It does not accept arbitrary user input and only writes a small placeholder file.
    const blob = await put('example.txt', 'Hello from Zopio storage example', {
      access: 'private'
    });

    return new Response(
      JSON.stringify({
        ok: true,
        url: blob.url,
        note:
          'This is a placeholder route. Replace with real upload logic for your project.'
      }),
      {
        status: 200,
        headers: {
          'content-type': 'application/json'
        }
      }
    );
  } catch (error) {
    return new Response(
      JSON.stringify({
        ok: false,
        error:
          'Failed to write to storage. Check BLOB_READ_WRITE_TOKEN and Vercel Blob configuration.'
      }),
      {
        status: 500,
        headers: {
          'content-type': 'application/json'
        }
      }
    );
  }
}
`,
    });
  }

  // Example rate-limited route (API app and rate limiting enabled)
  if (profile.apps.includes('api') && needsRateLimiting) {
    fileChanges.push({
      path: 'apps/api/app/rate-limited/ping/route.ts',
      type: 'create',
      description:
        'Add example route demonstrating basic Upstash-based rate limiting',
      operation: 'create_if_missing',
      content: `/**
 * SPDX-License-Identifier: MIT
 */

import { createRateLimiter, slidingWindow } from '@repo/rate-limit';

export async function GET(): Promise<Response> {
  const hasUpstashConfig =
    !!process.env.UPSTASH_REDIS_REST_URL &&
    !!process.env.UPSTASH_REDIS_REST_TOKEN;

  if (!hasUpstashConfig) {
    return new Response(
      JSON.stringify({
        ok: true,
        rateLimited: false,
        message:
          'Rate limiting example route. Configure UPSTASH_REDIS_REST_URL and UPSTASH_REDIS_REST_TOKEN to enable real limiting.'
      }),
      {
        status: 200,
        headers: {
          'content-type': 'application/json'
        }
      }
    );
  }

  const limiter = createRateLimiter({
    limiter: slidingWindow(10, '10 s'),
    prefix: 'zopio_rate_example'
  });

  const ip = 'anonymous';
  const { success, limit, remaining, reset } = await limiter.limit(
    \`ping_\${ip}\`
  );

  if (!success) {
    return new Response(
      JSON.stringify({
        ok: false,
        rateLimited: true,
        message: 'Too many requests. Please try again later.'
      }),
      {
        status: 429,
        headers: {
          'content-type': 'application/json',
          'retry-after': reset.toString()
        }
      }
    );
  }

  return new Response(
    JSON.stringify({
      ok: true,
      rateLimited: false,
      limit,
      remaining,
      reset
    }),
    {
      status: 200,
      headers: {
        'content-type': 'application/json'
      }
    }
  );
}
`,
    });
  }

  const summary = `Setup plan for ${profile.architecture.replace(
    '_',
    '-'
  )} project using apps: ${profile.apps.join(', ')}`;

  return {
    sessionId,
    profileId,
    summary,
    apps: profile.apps,
    prisma: {
      schemaPath: PRISMA_SCHEMA_PATH,
      template: prismaTemplate,
      primaryEntity: profile.primaryEntity,
    },
    fileChanges,
  };
}

export interface ApplyFileChangeResult extends AppliedFileChange {}

export interface ApplyPlanOptions {
  rootDir: string;
  changes: PlannedFileChange[];
}

export function resolvePath(rootDir: string, relativePath: string): string {
  return join(rootDir, relativePath);
}
